#!/usr/bin/env python3
"""Generates tools/FIXES.md: every change the build applies to the original game, in the order it applies them,
from the comments in tools/apply_entry_fix.py (the comments are the source of truth; this keeps a readable index
of them in step). Sections: the entry edits (head script, loading, VR entry), the gameplay and performance fixes
(B = bug, P = performance, L = license, D = diagnostics), the multiview edits, and the experiments.

    python3 -I tools/gen_fixes_doc.py           write tools/FIXES.md
    python3 -I tools/gen_fixes_doc.py --check   fail if tools/FIXES.md is out of date (quick test tier)
"""
import os, re, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'apply_entry_fix.py')
OUT = os.path.join(HERE, 'FIXES.md')


def blocks(lines, start, end):
    """Comment blocks at list indentation between two line numbers, each with the count of edit pairs after it."""
    out, cur = [], None
    for i in range(start, end):
        ln = lines[i]
        m = re.match(r'^ {4}# ?(.*)$', ln)
        if m:
            if cur is None or cur['closed']:
                cur = {'text': [], 'pairs': 0, 'closed': False, 'line': i + 1}
                out.append(cur)
            cur['text'].append(m.group(1))
            continue
        if cur is not None:
            cur['closed'] = True
            if re.match(r'^ {4}\(', ln):
                cur['pairs'] += 1
    return out


def ident(text):
    first = text[0].strip()
    m = re.match(r'^([A-Z]{1,2}\d+[a-z]?)\b', first) or re.match(r'^(\d+)\.', first)
    return m.group(1) if m else ''


def para(text):
    body = ' '.join(t.strip() for t in text).strip()
    return textwrap.fill(body, 100)


def main():
    src = open(SRC, encoding='utf-8').read()
    lines = src.split('\n')
    find = lambda pat: next(i for i, l in enumerate(lines) if re.match(pat, l))
    e0, g0 = find(r'^EDITS = \['), find(r'^GAME_FIXES = \[')
    g1 = next(i for i in range(g0, len(lines)) if lines[i] == ']')
    x0 = find(r'^EXPERIMENTS = \{')
    x1 = next(i for i in range(x0, len(lines)) if lines[i] == '}')
    mv = re.search(r'def _multiview\(\):\n    """(.*?)"""', src, re.S)
    edits, fixes = blocks(lines, e0, g0), blocks(lines, g0, g1)
    exps = []
    for m in re.finditer(r'^((?: {4}#.*\n)+) {4}"([a-z]+)":', '\n'.join(lines[x0:x1 + 1]) + '\n', re.M):
        exps.append((m.group(2), [re.sub(r'^ {4}# ?', '', l) for l in m.group(1).rstrip('\n').split('\n')]))
    md = ['# Fixes applied to the original game', '',
          'Generated by `tools/gen_fixes_doc.py` from the comments in `tools/apply_entry_fix.py`; do not edit by hand',
          '(the quick test tier fails when this file is out of date). The original is `tools/uncompressed.html`;',
          '`apply_entry_fix.py` applies these edits in this order and `--verify` checks the result is exactly that.',
          'IDs: numbers are the entry edits, B a bug fix (tools/BUGS.md), P a performance change (tools/PERF.md),',
          'L the license notice, D diagnostics. NOTES numbers point to tools/NOTES.md.', '',
          f'## Entry edits ({len(edits)} blocks)', '',
          'The head script and boot changes that launch the game straight into VR (RELEASE.md 6: any change here',
          'ships first as an experiment APK).', '']
    for b in edits:
        i = ident(b['text'])
        md += [f'- **{i or "(note)"}** ({b["pairs"]} edit{"s" if b["pairs"] != 1 else ""}): ' + para(b['text']).split(' ', 1)[-1] if i else '- ' + para(b['text']), '']
    md += [f'## Gameplay, performance and other fixes ({len(fixes)} blocks)', '']
    for b in fixes:
        i = ident(b['text'])
        body = para(b['text'])
        md += [f'- **{i}** ({b["pairs"]} edit{"s" if b["pairs"] != 1 else ""}): {body[len(i):].lstrip(" :")}' if i else f'- ({b["pairs"]} edit{"s" if b["pairs"] != 1 else ""}) {body}', '']
    if mv:
        md += ['## Multiview (release path since 3.15.34)', '', textwrap.dedent(mv.group(1)).strip(), '']
    md += ['## Experiments (never in the release; `tools/build_experiment.sh NAME`)', '']
    for name, text in exps:
        md += [f'- **{name}**: ' + para(text), '']
    doc = '\n'.join(md).rstrip('\n') + '\n'
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != doc:
            sys.exit('FIXES.md is out of date: run python3 -I tools/gen_fixes_doc.py')
        print('FIXES.md is up to date')
        return
    open(OUT, 'w', encoding='utf-8').write(doc)
    print(f'wrote {OUT}: {len(edits)} entry blocks, {len(fixes)} fix blocks, {len(exps)} experiments')


if __name__ == '__main__':
    main()
